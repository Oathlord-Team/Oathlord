using Content.Client.UserInterface;
using Content.Oathlord.Client.UserInterface.Systems.CharAttributes.Windows;
using Content.Oathlord.Shared.CharacterAttributes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Oathlord.Client.UserInterface.Systems.CharAttributes.Controls;

[GenerateTypedNameReferences]
public sealed partial class CharacterAttributeControl : BoxContainer, IEntityControl
{
    /// <summary>
    /// Points to add to this attribute
    /// </summary>
    private int _points;

    public event Action<int>? PointsChanged;

    private CharacterAttributeWindow _window;

    public CharacterAttributeControl(EntityUid attribute, CharacterAttributeWindow window, IEntityManager entMan)
    {
        RobustXamlLoader.Load(this);

        _window = window;
        UiEntity = attribute;

        if (!entMan.TryGetComponent<CharacterAttributeComponent>(attribute, out var charAttribute))
            return;

        var meta = entMan.GetComponent<MetaDataComponent>(attribute);
        var name = meta.EntityName;
        var desc = meta.EntityDescription;

        IconView.SetEntity(attribute);
        AttributeLabel.Text = $"{name} | {desc}";
        PointsLabel.Text = charAttribute.CurrentPoints.ToString();

        StrengthenButton.Text = $"Strengthen: {_points}";
        StrengthenButton.OnPressed += OnPressed;
    }

    private void OnPressed(BaseButton.ButtonEventArgs obj)
    {
        _points++;
        StrengthenButton.Text = $"Strengthen: {_points}";

        PointsChanged?.Invoke(_points);
    }

    public EntityUid? UiEntity { get; }
}

