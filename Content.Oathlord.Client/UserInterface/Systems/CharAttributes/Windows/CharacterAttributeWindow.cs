using Content.Client.UserInterface.Controls;
using Content.Oathlord.Client.UserInterface.Systems.CharAttributes.Controls;
using Content.Oathlord.Shared.CharacterAttributes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Oathlord.Client.UserInterface.Systems.CharAttributes.Windows;

[GenerateTypedNameReferences]
public sealed partial class CharacterAttributeWindow : FancyWindow
{
    private CharacterAttributesSystem? _charAttribute;

    private Dictionary<NetEntity, int> _changedAttributes = new();
    public event Action<Dictionary<NetEntity, int>>? ApplyChanges;

    public CharacterAttributeWindow()
    {
        RobustXamlLoader.Load(this);

        ApplyButton.OnPressed += ApplyButtonOnOnPressed;
    }

    public void Populate(EntityUid user, IEntityManager entMan)
    {
        _charAttribute ??= entMan.System<CharacterAttributesSystem>();
        AttributesContainer.Children.Clear();

        var attributes = _charAttribute.GetAttributes(user);
        foreach (var attribute in attributes)
        {
            var attrControl = new CharacterAttributeControl(attribute, this, entMan);
            attrControl.PointsChanged += points =>
            {
                _changedAttributes.Add(entMan.GetNetEntity(attribute), points);
                ApplyButton.Disabled = false;
            };

            AttributesContainer.AddChild(attrControl);
        }
    }

    public override void Close()
    {
        base.Close();

        ApplyButton.Disabled = true;
        _changedAttributes.Clear();
    }

    private void ApplyButtonOnOnPressed(BaseButton.ButtonEventArgs obj)
    {
        ApplyChanges?.Invoke(_changedAttributes);
    }
}

